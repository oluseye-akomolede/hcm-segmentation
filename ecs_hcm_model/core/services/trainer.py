# pylint: disable=import-error disable=no-name-in-module
from ecs_hcm_model.core.backbones import DEFAULT_BACKBONE
from ecs_hcm_model.core.hcm_nn import MASK_STRIDE_DEFAULT
from ecs_hcm_model.core.trainer import (
    train_hcm_imagenet1k,
)

def run_train_hcm_imagenet1k(
        new_model: bool = True,
        environment: str = "development",
        finetune: bool = False,
        coco: bool = False,
        model_base: str = "models",
        max_epochs: int = 5,
        batch_size: int = 8,
        test_mode: bool = False,
        warmup: bool = True,
        max_batches_per_epoch: int = 0,
        input_size: int = 192,
        coco_mix_ratio: float = 0.0,
        init_from: str | None = None,
        init_decoder_arch: str = "v2",
        backbone: str = DEFAULT_BACKBONE,
        neck_channels: int | None = None,
        mask_stride: int = MASK_STRIDE_DEFAULT,
        scale_jitter: tuple[float, float] | None = None,
        color_jitter: float | None = None,
        grad_accum_steps: int = 1,
        lr_decay_start: int | None = None,
        bdd: bool = False,
        bdd_data_root: str | None = None,
        bdd_coco_mix_share: float = 0.5,
        early_stop_monitor: str = "val_loss",
        early_stop_patience: int = 5,
        amodal_outline: bool = False,
        full_outline_weight: float = 1.0,
):
    train_hcm_imagenet1k(
        new_model=new_model,
        environment=environment,
        finetune=finetune,
        coco=coco,
        model_base=model_base,
        max_epochs=max_epochs,
        batch_size=batch_size,
        test_mode=test_mode,
        warmup=warmup,
        max_batches_per_epoch=max_batches_per_epoch,
        input_size=input_size,
        coco_mix_ratio=coco_mix_ratio,
        init_from=init_from,
        init_decoder_arch=init_decoder_arch,
        backbone=backbone,
        neck_channels=neck_channels,
        mask_stride=mask_stride,
        scale_jitter=scale_jitter,
        color_jitter=color_jitter,
        grad_accum_steps=grad_accum_steps,
        lr_decay_start=lr_decay_start,
        bdd=bdd,
        bdd_data_root=bdd_data_root,
        bdd_coco_mix_share=bdd_coco_mix_share,
        early_stop_monitor=early_stop_monitor,
        early_stop_patience=early_stop_patience,
        amodal_outline=amodal_outline,
        full_outline_weight=full_outline_weight,
    )